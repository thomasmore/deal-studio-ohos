'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const file = path.join(__dirname, 'texture-renderer-check.js')
let source = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
source = source.replace('main().catch(error => { console.error(error.stack || error); process.exitCode = 1 })',
  'module.exports = {fixture, body, world, theme, resolveTheme, T, L}')
source = source.replace('const made = make()\n        resources.push(made)', `const made = make()
        if (op === 'material' || op === 'image') {
          made.destroys = 0
          made.destroy = function () {
            assert.equal(scene.destroys, 0)
            assert.equal(this.destroys++, 0, 'resource destroyed exactly once')
            if (op === 'material') assert.ok(this.baseColor.image == null)
            record('resourceDestroy', this.name, scene)
          }
        }
        resources.push(made)`)
source = source.replace('const fileIo = {', `let stamp = 0
  const times = new Map(), symlinks = new Set()
  const fileIo = {
    listFileSync(dir) {
      record('list', dir)
      return [...new Set([...files.keys(), ...dirs, ...symlinks])]
        .filter(p => p.startsWith(dir + '/') && !p.slice(dir.length + 1).includes('/')).map(p => p.slice(dir.length + 1))
    },
    lstatSync(file) {
      record('lstat', file)
      return {isFile: () => files.has(file) && !symlinks.has(file), isSymbolicLink: () => symlinks.has(file), mtime: times.get(file) || 0}
    },`)
source = source.replace('files.set(to, files.get(from))', 'files.set(to, files.get(from)); times.set(to, ++stamp)')
source = source.replace('return {calls, scenes, resources, maps, packers, files, dirs, handles, faults, logs, loaded, settle, clean,',
  'return {calls, scenes, resources, maps, packers, files, dirs, symlinks, times, handles, faults, logs, loaded, settle, clean,')
const mod = new Module(file, module)
mod.filename = file
mod.paths = Module._nodeModulePaths(__dirname)
mod._compile(source, file)
const {fixture, body, world, theme, resolveTheme, T, L} = mod.exports
const dir = '/mock-app/files/vera/tex/'
const managed = name => /^tex_v2_256_(wood|planks|brick|tiles|stone|grass|sand|metal|marble|checker|fabric|plain)_[0-9a-f]{48}_[0-9a-f]{48}_[0-9a-f]{1,8}\.png$/.test(name)
const pngs = f => [...f.files.keys()].filter(p => managed(p.slice(dir.length)) && !f.symlinks.has(p))
const material = node => node.mesh.subMeshes[0].material

async function main() {
  let f = fixture(), box = await f.create()
  for (let i = 0; i < 1000; i++) {
    await f.apply(box, world([body('turnover-' + i)]))
    assert.equal(box.resolvedMaterials.size, 1)
    assert.equal(box.resolvedImages.size, 1)
    assert.equal(box.textureSamplers.size, 1)
    assert.equal(box.materialBindings.size, 1)
    assert.equal(f.resources.filter(r => r.baseColor && r.destroys === 0).length, 1)
    assert.ok(pngs(f).length <= 256)
    if (i % 50 === 0) { f.maps.length = 0; f.packers.length = 0 }
  }
  assert.equal(pngs(f).length, 256)
  assert.ok(f.calls.filter(c => c.op === 'resourceDestroy').length >= 999 * 2)
  assert.ok([...box.textureSamplers].every(s => s.destroy === undefined))
  await f.apply(box, world([]))
  assert.equal(box.resolvedMaterials.size + box.resolvedImages.size + box.textureSamplers.size, 0)
  f.destroy()
  console.log('PASS 1000 seeded-id turnover: 1 live material/image; 1 tracked sampler without destroy API; 0 idle; disk plateau 256')

  f = fixture(); box = await f.create()
  const group = body('group', 'group', {pattern: '', parts: [body('part-a'), body('part-b')]})
  const ball = body('planet', 'sphere', {pattern: 'bands', rings: [1, 1.2], mark: 'accent'})
  for (let i = 0; i < 12; i++) {
    const palette = resolveTheme('clean', i % 2 ? '#cc2244' : '#2244cc', false)
    const spec = world([group, ball])
    spec.floor = {color: 'surface', color2: 'ink', pattern: 'wood'}
    spec.table = {width: 3, depth: 2, color: 'accent', color2: 'ink', pattern: 'tiles'}
    await f.apply(box, spec, palette)
    for (const m of box.materialBindings.values()) assert.equal(m.destroys, 0)
    for (const m of box.resolvedMaterials.values()) {
      if (m.baseColor.image) assert.equal(m.baseColor.image.destroys, 0)
    }
    assert.ok(box.resolvedImages.size <= 4)
  }
  const first = [0.2, 0.3, 0.4, 1], second = [0.7, 0.8, 0.9, 1]
  const sharedA = await f.settle(box.texturedMaterial('wood', first, second, 7, false, true))
  const sharedB = await f.settle(box.texturedMaterial('wood', first, second, 7, true, false))
  const image = sharedA.baseColor.image
  assert.equal(image, sharedB.baseColor.image)
  box.paint(box.floorNodes[0], sharedA)
  box.paint(box.bodies.get('group').parts[0], sharedB)
  box.sweepMaterials(); assert.equal(image.destroys, 0)
  box.paint(box.floorNodes[0], sharedB)
  box.sweepMaterials(); assert.equal(sharedA.destroys, 1); assert.equal(image.destroys, 0)
  await f.apply(box, world([])); assert.equal(sharedB.destroys, 1); assert.equal(image.destroys, 1)
  f.destroy()
  console.log('PASS theme/group/legacy rings/ground sweeps; shared image survives until last bound material leaves')

  f = fixture(); box = await f.create()
  const key = n => T.textureKey('wood', first, second, n) + '.png'
  for (let i = 0; i < 260; i++) f.files.set(dir + key(i), Buffer.from([1]))
  const unrelated = ['spike-256-0.png', 'notes.txt', 'tex_v1_256_wood.png', key(999) + '.tmp', '../outside.png']
  for (const name of unrelated) f.files.set(dir + name, Buffer.from([1]))
  f.dirs.add(dir + key(900))
  f.symlinks.add(dir + key(901)); f.files.set(dir + key(901), Buffer.from([1]))
  const gate = f.hold('image', key(0).slice(0, -4))
  const held = box.textureImage(key(0).slice(0, -4), 'wood', first, second, 0)
  await f.settle(gate.entered.promise)
  const other = await f.create()
  await f.settle(other.textureImage(key(902).slice(0, -4), 'wood', first, second, 902))
  assert.ok(f.files.has(dir + key(0)), 'pending createImage source is pinned across boxes')
  gate.release.resolve(); await f.settle(held)
  assert.ok(pngs(f).length <= 256)
  for (const name of unrelated) assert.ok(f.files.has(dir + name))
  assert.ok(f.dirs.has(dir + key(900))); assert.ok(f.symlinks.has(dir + key(901)))
  f.destroy()
  console.log('PASS concurrent image load pins source; strict v2-only trimming ignores unrelated files, directories and symlinks')

  f = fixture(); box = await f.create()
  for (let i = 0; i < 260; i++) f.files.set(dir + key(i), Buffer.from([1]))
  const allGate = f.hold('image')
  const loads = Array.from({length: 260}, (_, i) => box.textureImage(key(i).slice(0, -4), 'wood', first, second, i))
  await f.settle(allGate.entered.promise)
  for (let i = 0; i < 20; i++) await Promise.resolve()
  assert.equal(f.count('image'), 260)
  assert.equal(pngs(f).length, 260, 'all in-use files may transiently exceed the disk cap')
  allGate.release.resolve(); await f.settle(Promise.all(loads))
  assert.equal(pngs(f).length, 256)
  box.sweepMaterials(); assert.equal(box.resolvedImages.size, 0)
  f.destroy()
  console.log('PASS all-pinned transient overflow returns to 256 after the final image load')

  f = fixture(); box = await f.create()
  await f.apply(box, world([body('stable')]))
  const stable = material(box.bodies.get('stable').node)
  f.faults.add('geometry')
  box.apply(world([body('failed')]), theme)
  await f.settle((async () => { while (box.running) await Promise.resolve() })())
  assert.match(box.note, /failed/)
  f.faults.clear()
  await f.apply(box, world([body('recovered')]))
  assert.equal(stable.destroys, 1)
  assert.equal(box.resolvedMaterials.size, 1)
  assert.equal(box.resolvedImages.size, 1)
  f.destroy()
  console.log('PASS failed apply defers sweep; successful retry reclaims historical and unbound resources')

  f = fixture(); box = await f.create()
  const failing = body('first'), delayed = body('second')
  const failingKey = T.textureKey(failing.pattern, L.lookRgba(theme, failing.color), L.lookRgba(theme, failing.color2),
    require('./source-loader').loadVera('VeraSurfaces').surfaceSeed(failing.id))
  const failingMaterial = await f.settle(box.bodyMaterial(failing, false, theme))
  const delayedMaterial = await f.settle(box.bodyMaterial(delayed, false, theme))
  let sweepCount = 0
  const sweep = box.sweepMaterials.bind(box)
  box.sweepMaterials = () => { sweepCount++; sweep() }
  const delayedGate = f.hold('mesh', 'b2m')
  f.faults.add('mesh:b1m')
  const attempted = world([failing, delayed])
  box.apply(attempted, theme)
  await f.settle(delayedGate.entered.promise)
  for (let i = 0; i < 40; i++) await Promise.resolve()
  assert.equal(box.resourcePending, 0, 'materials resolved before the pending node operation')
  assert.equal(box.running, true, 'a failed sibling cannot finish the apply while another node is pending')
  assert.equal(sweepCount, 0)
  const retry = world([delayed])
  box.apply(retry, theme)
  for (let i = 0; i < 40; i++) await Promise.resolve()
  assert.equal(box.running, true)
  assert.equal(box.appliedSpec(), null)
  assert.equal(delayedMaterial.destroys, 0)
  delayedGate.release.resolve()
  await f.settle((async () => { while (box.running) await Promise.resolve() })())
  assert.match(box.note, /mesh:b1m/)
  assert.equal(sweepCount, 0, 'failed fully drained batch does not sweep')
  assert.equal(box.bodies.get('second').node.mesh.subMeshes[0].material, delayedMaterial)
  f.faults.clear()
  await f.apply(box, retry)
  assert.equal(box.bodyCount(), 1)
  assert.equal(box.bodies.get('second').node.mesh.subMeshes[0].material, delayedMaterial)
  assert.equal(delayedMaterial.destroys, 0)
  assert.equal(failingMaterial.destroys, 1)
  assert.equal(box.materials.has('texture:' + failingKey + ':false:false:1:false'), false)
  assert.equal(sweepCount, 1)
  f.destroy()
  console.log('PASS failed mesh drains delayed sibling before releasing pump; retry cannot sweep or destroy its resolved material early')

  for (const keepStable of [false, true]) {
    f = fixture(); box = await f.create()
    const stableSpec = body('stable', 'box', {pattern: ''})
    await f.apply(box, world([stableSpec]))
    const stableEntry = box.bodies.get('stable'), sharedMaterial = material(stableEntry.node)
    const failedName = 'b' + (box.serial + 1), siblingName = 'b' + (box.serial + 2)
    const gate = f.hold('geometry', siblingName)
    f.faults.add('mesh:' + failedName + 'm')
    box.apply(world([stableSpec, body('failure'), body('sibling', 'box', {pattern: ''})]), theme)
    await f.settle(gate.entered.promise)
    for (let i = 0; i < 40; i++) await Promise.resolve()
    assert.equal(box.running, true)
    assert.equal(sharedMaterial.destroys, 0)
    assert.equal(stableEntry.node.destroys, 0)
    gate.release.resolve()
    await f.settle((async () => { while (box.running) await Promise.resolve() })())
    assert.match(box.note, /World rendering failed:/)
    const sibling = box.bodies.get('sibling').node
    assert.equal(material(sibling), sharedMaterial)
    f.faults.clear()
    await f.apply(box, world(keepStable ? [stableSpec] : []))
    assert.equal(box.bodyCount(), keepStable ? 1 : 0)
    assert.equal(sibling.destroys, 1)
    assert.equal(sibling.parent, null)
    assert.equal(box.materialBindings.has(sibling.name), false)
    assert.equal(sharedMaterial.destroys, keepStable ? 0 : 1)
    if (keepStable) assert.equal(box.bodies.get('stable'), stableEntry)
    await f.apply(box, world([]))
    assert.equal(sharedMaterial.destroys, 1)
    assert.equal(box.materialBindings.size + box.resolvedMaterials.size + box.resolvedImages.size + box.textureSamplers.size, 0)
    f.destroy()
  }
  console.log('PASS superseded partial bodies are removed on retry to empty or stable world; shared live material survives')

  f = fixture(); box = await f.create()
  const pipOwner = body('pip-owner', 'box', {pattern: '', color: L.LOOK_PIP_ROLE})
  await f.apply(box, world([pipOwner]))
  const ownerEntry = box.bodies.get(pipOwner.id), pipMaterial = material(ownerEntry.node)
  const die = body('die', 'box', {isDie: true})
  const dieName = 'b' + (box.serial + 1), failedPip = 'p' + (box.serial + 2), delayedPip = 'p' + (box.serial + 3)
  const pipGate = f.hold('geometry', delayedPip)
  f.faults.add('mesh:' + failedPip + 'm')
  box.apply(world([pipOwner, die]), theme)
  await f.settle(pipGate.entered.promise)
  for (let i = 0; i < 40; i++) await Promise.resolve()
  assert.equal(box.running, true)
  assert.equal(f.calls.filter(c => c.op === 'nodeDestroy').length, 0)
  assert.equal(pipMaterial.destroys, 0)
  pipGate.release.resolve()
  await f.settle((async () => { while (box.running) await Promise.resolve() })())
  assert.match(box.note, /World rendering failed:/)
  assert.equal(box.bodies.get('die').node.name, dieName)
  const orphanPips = [...new Set(f.resources.filter(r => /^p\d+$/.test(r.name) && r.children))]
  assert.equal(orphanPips.length, 20)
  assert.ok(orphanPips.every(pip => pip.parent === null && pip.destroys === 1))
  assert.equal(box.materialBindings.size, 2)
  assert.equal(pipMaterial.destroys, 0)
  f.faults.clear()
  await f.apply(box, world([pipOwner, die]))
  assert.equal(box.bodies.get(pipOwner.id), ownerEntry)
  assert.equal(box.bodies.get('die').pips.length, 21)
  assert.ok(box.bodies.get('die').pips.every(pip => material(pip) === pipMaterial))
  assert.equal(pipMaterial.destroys, 0)
  await f.apply(box, world([pipOwner]))
  assert.equal(box.materialBindings.size, 1)
  assert.equal(pipMaterial.destroys, 0)
  await f.apply(box, world([]))
  assert.equal(pipMaterial.destroys, 1)
  assert.equal(box.materialBindings.size + box.resolvedMaterials.size + box.resolvedImages.size + box.textureSamplers.size, 0)
  f.destroy()
  console.log('PASS failed pip batch drains before cleanup; all 20 successful pips removed once; shared material survives retry and die removal')
}
main().catch(error => { console.error(error.stack || error); process.exitCode = 1 })
